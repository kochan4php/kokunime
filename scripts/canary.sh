#!/usr/bin/env bash
# Weighted canary rollout for the production stack. Runs ON the deployment
# server (same directory as docker-compose.prod.yml, like deploy.sh).
#
#   ./canary.sh start <tag> [weight]   # weight 1..10 (default 1) on the canary
#   ./canary.sh watch [minutes]        # 5-min health gate; abort on failure, else promote
#   ./canary.sh abort                  # drop canary, stable takes all traffic
#   ./canary.sh promote <tag>          # stop canary + deploy.sh <tag>
set -euo pipefail

cd "$(dirname "$0")"
COMPOSE=(docker compose -f docker-compose.prod.yml -f docker-compose.canary.yml)
NGINX_CONF="nginx-canary.conf"
NGINX_CONTAINER="kokunime-nginx"
HEALTH_CANARY="http://localhost:3001/api/live"

write_conf() { # stable_weight canary_weight (0 = disabled)
  local stable="$1" canary="$2" canary_line
  if [ "$canary" -gt 0 ]; then
    canary_line="    server kokunime-canary:3000 weight=${canary} max_fails=3 fail_timeout=15s;"
  else
    canary_line="    # canary disabled (scripts/canary.sh manages this line)"
  fi
  cat > "$NGINX_CONF" <<EOF
# Generated by canary.sh — do NOT edit by hand (the repo copy is a seed).

# Microcaching: identical SSR requests within 1s share one render, which
# absorbs bursts without making content meaningfully stale. X-Cache-Status
# exposes HIT/MISS for debugging.
proxy_cache_path /tmp/nginx-microcache levels=1:2 keys_zone=kokunime_micro:10m max_size=200m inactive=10m use_temp_path=off;

upstream kokunime_backend {
    server kokunime:3000 weight=${stable} max_fails=3 fail_timeout=15s;
${canary_line}
    keepalive 16;
}

server {
    listen 80;
    gzip on;
    gzip_proxied any;
    gzip_types text/plain text/css application/json application/javascript text/xml application/xml image/svg+xml;
    gzip_min_length 1024;

    location = /healthz {
        return 200 "ok\n";
        add_header Content-Type text/plain;
    }

    # APIs and admin never hit the microcache (mutations + per-token views).
    location /api/ {
        proxy_pass http://kokunime_backend;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header X-Request-Start "\${msec}";
        proxy_set_header Connection "";
        proxy_read_timeout 30s;
        proxy_connect_timeout 5s;
        proxy_cache off;
    }

    location / {
        proxy_pass http://kokunime_backend;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        # Middleware reads this for real request age in sampled logs.
        proxy_set_header X-Request-Start "\${msec}";
        proxy_set_header Connection "";
        proxy_read_timeout 30s;
        proxy_connect_timeout 5s;

        proxy_cache kokunime_micro;
        proxy_cache_valid 200 301 302 1s;
        proxy_cache_lock on;
        proxy_cache_use_stale updating error timeout;
        proxy_cache_background_update on;
        # Responses that set cookies (personalized) stay uncached by default.
        add_header X-Cache-Status \$upstream_cache_status always;
    }
}
EOF
  docker exec "$NGINX_CONTAINER" nginx -s reload >/dev/null 2>&1 || true
}

case "${1:-}" in
  start)
    TAG="${2:?usage: canary.sh start <tag> [weight]}"
    WEIGHT="${3:-1}"
    if ! [ "$WEIGHT" -ge 1 ] 2>/dev/null || [ "$WEIGHT" -gt 10 ]; then
      echo "weight must be an integer 1..10" >&2
      exit 2
    fi
    export KOKUNIME_CANARY_TAG="$TAG"
    echo "starting canary $TAG (weight ${WEIGHT}/10)"

    [ -f "$NGINX_CONF" ] || cp nginx-canary-seed.conf "$NGINX_CONF"
    "${COMPOSE[@]}" up -d kokunime nginx kokunime-canary

    for _ in $(seq 1 24); do
      if curl -fsS --max-time 5 "$HEALTH_CANARY" >/dev/null 2>&1; then break; fi
      sleep 5
    done
    if ! curl -fsS --max-time 5 "$HEALTH_CANARY" >/dev/null 2>&1; then
      echo "canary failed its liveness gate — stopping it"
      "${COMPOSE[@]}" stop kokunime-canary || true
      exit 1
    fi

    write_conf 10 "$WEIGHT"
    echo "$TAG" > .canary-tag
    echo "canary live: ${WEIGHT} canary / 10 stable via nginx. Watch errors, then promote or abort."
    ;;

  abort)
    "${COMPOSE[@]}" stop kokunime-canary || true
    write_conf 10 0
    rm -f .canary-tag
    echo "canary stopped; stable serves all traffic"
    ;;

  # Health-gated observation window: aborts (auto-rollback) after 3 consecutive
  # failed probes, otherwise promotes the canary automatically when the window
  # ends clean.
  watch)
    MINUTES="${2:-5}"
    if [ ! -f .canary-tag ]; then
      echo "no .canary-tag file — run 'canary.sh start <tag>' first" >&2
      exit 2
    fi
    TAG="$(cat .canary-tag)"
    WATCH_END=$(( $(date +%s) + MINUTES * 60 ))
    FAILS=0
    echo "watching canary $TAG for ${MINUTES}m (probe every 15s, abort after 3 fails)"
    while [ "$(date +%s)" -lt "$WATCH_END" ]; do
      sleep 15
      if curl -fsS --max-time 5 "$HEALTH_CANARY" >/dev/null 2>&1; then
        FAILS=0
      else
        FAILS=$((FAILS + 1))
        echo "canary probe failed (${FAILS}/3)"
        if [ "$FAILS" -ge 3 ]; then
          echo "auto-rollback: canary unhealthy, dropping it"
          "${COMPOSE[@]}" stop kokunime-canary || true
          write_conf 10 0
          rm -f .canary-tag
          exit 1
        fi
      fi
    done

    echo "watch window clean — auto-promoting $TAG"
    "${COMPOSE[@]}" stop kokunime-canary || true
    write_conf 10 0
    ./deploy.sh "$TAG"
    "${COMPOSE[@]}" up -d nginx
    rm -f .canary-tag
    echo "promoted $TAG to stable (auto)"
    ;;

  promote)
    TAG="${2:?usage: canary.sh promote <tag>}"
    "${COMPOSE[@]}" stop kokunime-canary || true
    write_conf 10 0
    rm -f .canary-tag
    ./deploy.sh "$TAG"
    "${COMPOSE[@]}" up -d nginx
    echo "promoted $TAG to stable"
    ;;

  *)
    echo "usage: canary.sh start <tag> [weight] | watch [minutes] | abort | promote <tag>" >&2
    exit 2
    ;;
esac
