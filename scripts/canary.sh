#!/usr/bin/env bash
# Weighted canary rollout for the production stack. Runs ON the deployment
# server (same directory as docker-compose.prod.yml, like deploy.sh).
#
#   ./canary.sh start <tag> [weight]   # weight 1..10 (default 1) on the canary
#   ./canary.sh abort                  # drop canary, stable takes all traffic
#   ./canary.sh promote <tag>          # stop canary + deploy.sh <tag>
set -euo pipefail

cd "$(dirname "$0")"
COMPOSE=(docker compose -f docker-compose.prod.yml -f docker-compose.canary.yml)
NGINX_CONF="nginx-canary.conf"
NGINX_CONTAINER="kokunime-nginx"
HEALTH_CANARY="http://localhost:3001/api/live"

write_conf() { # stable_weight canary_weight (0 = disabled)
  local stable="$1" canary="$2" canary_line
  if [ "$canary" -gt 0 ]; then
    canary_line="    server kokunime-canary:3000 weight=${canary} max_fails=3 fail_timeout=15s;"
  else
    canary_line="    # canary disabled (scripts/canary.sh manages this line)"
  fi
  cat > "$NGINX_CONF" <<EOF
# Generated by canary.sh — do NOT edit by hand (the repo copy is a seed).
upstream kokunime_backend {
    server kokunime:3000 weight=${stable} max_fails=3 fail_timeout=15s;
${canary_line}
}

server {
    listen 80;

    location = /healthz {
        return 200 "ok\n";
        add_header Content-Type text/plain;
    }

    location / {
        proxy_pass http://kokunime_backend;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header X-Request-Start "\${msec}";
        proxy_read_timeout 30s;
        proxy_connect_timeout 5s;
    }
}
EOF
  docker exec "$NGINX_CONTAINER" nginx -s reload >/dev/null 2>&1 || true
}

case "${1:-}" in
  start)
    TAG="${2:?usage: canary.sh start <tag> [weight]}"
    WEIGHT="${3:-1}"
    if ! [ "$WEIGHT" -ge 1 ] 2>/dev/null || [ "$WEIGHT" -gt 10 ]; then
      echo "weight must be an integer 1..10" >&2
      exit 2
    fi
    export KOKUNIME_CANARY_TAG="$TAG"
    echo "starting canary $TAG (weight ${WEIGHT}/10)"

    [ -f "$NGINX_CONF" ] || cp nginx-canary-seed.conf "$NGINX_CONF"
    "${COMPOSE[@]}" up -d kokunime nginx kokunime-canary

    for _ in $(seq 1 24); do
      if curl -fsS --max-time 5 "$HEALTH_CANARY" >/dev/null 2>&1; then break; fi
      sleep 5
    done
    if ! curl -fsS --max-time 5 "$HEALTH_CANARY" >/dev/null 2>&1; then
      echo "canary failed its liveness gate — stopping it"
      "${COMPOSE[@]}" stop kokunime-canary || true
      exit 1
    fi

    write_conf 10 "$WEIGHT"
    echo "canary live: ${WEIGHT} canary / 10 stable via nginx. Watch errors, then promote or abort."
    ;;

  abort)
    "${COMPOSE[@]}" stop kokunime-canary || true
    write_conf 10 0
    echo "canary stopped; stable serves all traffic"
    ;;

  promote)
    TAG="${2:?usage: canary.sh promote <tag>}"
    "${COMPOSE[@]}" stop kokunime-canary || true
    write_conf 10 0
    ./deploy.sh "$TAG"
    "${COMPOSE[@]}" up -d nginx
    echo "promoted $TAG to stable"
    ;;

  *)
    echo "usage: canary.sh start <tag> [weight] | abort | promote <tag>" >&2
    exit 2
    ;;
esac
